#!/usr/bin/env python3
"""Generate the static accepted-paper catalogue and individual pages (Python 3)."""
import argparse
import json
import re
from html import escape
from pathlib import Path
from string import Template
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by scripts/build-papers.py; edit data/papers.json instead. -->'


def text(value, label):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'{label} must be a nonempty string')
    return value


def media_url(value, label):
    text(value, label)
    parsed = urlsplit(value)
    if parsed.scheme or parsed.netloc:
        if parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password:
            raise ValueError(f'{label} must use HTTPS')
    elif not value.startswith('assets/') or '..' in parsed.path.split('/') or '\\' in value:
        raise ValueError(f'{label} must be an HTTPS URL or a path under assets/')
    return value


def validate(papers):
    if not isinstance(papers, list):
        raise ValueError('Paper data must be a JSON array')
    slugs = set()
    for paper in papers:
        if not isinstance(paper, dict):
            raise ValueError('Each paper must be an object')
        slug = text(paper.get('slug'), 'slug')
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug) or slug in slugs:
            raise ValueError(f'Invalid or duplicate slug: {slug}')
        slugs.add(slug)
        for field in ('title', 'abstract'):
            text(paper.get(field), f'{slug}.{field}')
        authors = paper.get('authors')
        if not isinstance(authors, list) or not authors:
            raise ValueError(f'{slug}.authors must be a nonempty list of names')
        for author in authors:
            text(author, f'{slug}.author')
        presentation = paper.get('presentation')
        if not isinstance(presentation, dict):
            raise ValueError(f'{slug}.presentation must be an object')
        kind = presentation.get('type')
        if kind == 'poster':
            if presentation.get('session') not in ('morning', 'afternoon'):
                raise ValueError(f'{slug}: poster session must be morning or afternoon')
        elif kind == 'oral':
            if not isinstance(presentation.get('time'), str) or not re.fullmatch(r'(?:[01][0-9]|2[0-3]):[0-5][0-9]', presentation['time']):
                raise ValueError(f'{slug}: oral time must be HH:MM (Paris local time)')
        else:
            raise ValueError(f'{slug}: presentation type must be poster or oral')
        if paper.get('pdf'):
            media_url(paper['pdf'], f'{slug}.pdf')
        video = paper.get('video')
        if video:
            if not isinstance(video, dict) or video.get('type') not in ('file', 'youtube', 'vimeo', 'loom'):
                raise ValueError(f'{slug}: video type must be file, youtube, vimeo, or loom')
            if video['type'] == 'file':
                media_url(video.get('url'), f'{slug}.video.url')
                if not urlsplit(video['url']).path.lower().endswith(('.mp4', '.webm')):
                    raise ValueError(f'{slug}: video file must be MP4 or WebM')
                if video.get('captions'):
                    media_url(video['captions'], f'{slug}.video.captions')
            else:
                patterns = {'youtube': r'[A-Za-z0-9_-]{11}', 'vimeo': r'[0-9]+', 'loom': r'[a-f0-9]{32}'}
                if not isinstance(video.get('id'), str) or not re.fullmatch(patterns[video['type']], video['id']):
                    raise ValueError(f'{slug}: invalid {video["type"]} video ID')


def schedule(paper):
    presentation = paper['presentation']
    if presentation['type'] == 'oral':
        time = presentation['time']
        return f'Oral presentation · <time datetime="2026-12-13T{time}:00+01:00">{time}</time> (Paris time)'
    return f'Poster session · {presentation["session"].capitalize()} <span class="schedule-tbd">(time TBD)</span>'


def resolve(url, prefix):
    return escape(url if urlsplit(url).scheme else prefix + url, quote=True)


def video_section(video):
    if not video:
        return ''
    heading = '<section class="paper-section" aria-labelledby="video-heading"><h2 id="video-heading">Virtual video poster</h2><p class="paper-note">A five-minute presentation from the authors.</p>'
    if video['type'] == 'file':
        url = resolve(video['url'], '../')
        track = ''
        if video.get('captions'):
            track = f'<track kind="captions" src="{resolve(video["captions"], "../")}" srclang="en" label="English" default>'
        return heading + f'<video class="paper-video" controls preload="none" playsinline src="{url}">{track}<p><a href="{url}">Open the video poster</a></p></video><p><a class="text-link" href="{url}">Open video in a new tab ↗</a></p></section>'
    ident = video['id']
    embed, watch = {
        'youtube': (f'https://www.youtube-nocookie.com/embed/{ident}', f'https://www.youtube.com/watch?v={ident}'),
        'vimeo': (f'https://player.vimeo.com/video/{ident}', f'https://vimeo.com/{ident}'),
        'loom': (f'https://www.loom.com/embed/{ident}', f'https://www.loom.com/share/{ident}'),
    }[video['type']]
    return heading + f'''<div class="video-embed" data-video-embed="{embed}">
      <div class="video-placeholder"><p>The player is hosted by {escape(video['type'].capitalize())}.</p>
      <button class="button button-primary" type="button" data-load-video>Load video poster <span aria-hidden="true">▶</span></button></div>
    </div><p><a class="text-link" href="{watch}" target="_blank" rel="noopener noreferrer">Watch on {escape(video['type'].capitalize())} ↗</a></p></section>'''


def detail(paper):
    title = escape(paper['title'])
    abstract = ''.join(f'<p>{escape(paragraph).replace(chr(10), "<br>")}</p>' for paragraph in paper['abstract'].split('\n\n') if paragraph.strip())
    pdf = '<p class="paper-note">The authors have not made a PDF available on this website.</p>'
    if paper.get('pdf'):
        url = resolve(paper['pdf'], '../')
        pdf = f'''<p><a class="text-link" href="{url}" target="_blank" rel="noopener noreferrer">Open PDF in a new tab ↗</a></p>
          <object class="paper-pdf" data="{url}" type="application/pdf" aria-label="PDF of {title}">
            <p>Your browser cannot display this PDF. <a href="{url}">Open the paper PDF</a>.</p>
          </object>'''
    return f'''<section class="papers-hero"><div class="shell">
      <a class="text-link" href="../papers.html">← All accepted papers</a>
      <p class="eyebrow paper-eyebrow">Accepted paper · NeurIPS 2026 workshop</p>
      <h1 class="paper-title">{title}</h1>
      <p class="paper-authors">{escape(', '.join(paper['authors']))}</p>
      <p class="paper-schedule">{schedule(paper)}</p>
      <p class="paper-note">13 December 2026 · Paris, France</p>
    </div></section>
    <div class="shell paper-content">
      <section class="paper-section" aria-labelledby="abstract-heading"><h2 id="abstract-heading">Abstract</h2><div class="paper-abstract">{abstract}</div></section>
      <section class="paper-section" aria-labelledby="pdf-heading"><h2 id="pdf-heading">Paper</h2>{pdf}</section>
      {video_section(paper.get('video'))}
    </div>'''


def catalogue(papers):
    rows = ''.join(f'''<li class="paper-row"><div>
      <h2><a href="papers/{paper['slug']}.html">{escape(paper['title'])}</a></h2>
      <p class="paper-authors">{escape(', '.join(paper['authors']))}</p>
      <a class="text-link" href="papers/{paper['slug']}.html">Abstract &amp; materials <span aria-hidden="true">→</span></a>
    </div><p class="paper-schedule">{schedule(paper)}</p></li>''' for paper in papers)
    body = f'<p class="catalogue-count">{len(papers)} accepted {"paper" if len(papers) == 1 else "papers"}</p><ul class="paper-list">{rows}</ul>' if papers else '''<div class="papers-empty"><h2>Accepted papers coming soon</h2><p>Submissions are closed. The accepted-paper list and presentation schedule will be published here soon.</p></div>'''
    return f'''<section class="papers-hero"><div class="shell">
      <p class="eyebrow">Workshop contributions · 13 December 2026</p>
      <h1>Accepted papers</h1>
      <p class="papers-lead">Explore the research presented at Representations for the Physical Sciences.</p>
      <p class="paper-note">Oral presentation times are local to Paris (CET). Morning and afternoon poster session times will be announced.</p>
    </div></section><section class="shell papers-catalogue" aria-label="Accepted paper catalogue">{body}</section>'''


def build(source, output):
    papers = json.loads(source.read_text())
    validate(papers)
    layout = Template((ROOT / 'templates/papers-layout.html').read_text())
    pages = {'papers.html': layout.substitute(prefix='', title='Accepted papers', description='Accepted papers and presentation schedules for the RPS workshop at NeurIPS 2026.', content=catalogue(papers))}
    for paper in papers:
        pages[f'papers/{paper["slug"]}.html'] = layout.substitute(prefix='../', title=escape(paper['title']), description=escape(f'{paper["title"]} — {", ".join(paper["authors"])}. Accepted at the RPS workshop, NeurIPS 2026.', quote=True), content=detail(paper))
    # Only remove our own generated pages when a paper is removed from the data.
    for old in (output / 'papers').glob('*.html'):
        if str(old.relative_to(output)) not in pages and MARKER in old.read_text():
            old.unlink()
    for name, content in pages.items():
        path = output / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content.replace('<html lang="en">', '<html lang="en">\n' + MARKER, 1))
    print(f'Generated catalogue and {len(papers)} paper pages in {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=ROOT / 'data/papers.json')
    parser.add_argument('--output', type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        build(args.data, args.output)
    except (ValueError, OSError) as error:
        parser.exit(1, f'Cannot build paper pages: {error}\n')
